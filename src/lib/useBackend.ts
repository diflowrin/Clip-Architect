/**
 * Bridges the Rust-side backend supervisor to React.
 *
 * The Rust shell starts the Python sidecar off-thread and reports progress over
 * the `backend://status` event. The event can fire before React mounts, so this
 * also reads the current status once on mount rather than relying on the event
 * alone.
 */

import { useEffect, useMemo, useState } from 'react';
import { invoke } from '@tauri-apps/api/core';
import { listen } from '@tauri-apps/api/event';

import { BackendApi } from './api';

export interface BackendInfo {
  base_url: string;
  data_dir: string;
  /**
   * The key every request to the backend has to carry.
   *
   * Generated by the shell for this launch and never written to disk, so there
   * is nothing to configure and nothing to leak between sessions. It arrives
   * with the base URL because the two are useless apart: the backend refuses
   * every route without it.
   */
  api_key: string;
}

export type BackendStatus =
  | { state: 'starting' }
  | ({ state: 'ready' } & BackendInfo)
  | { state: 'failed'; message: string }
  // Came up, served, then exited. The shell watches the child process and
  // pushes this, which is what stops the UI from insisting the backend is
  // running while every request fails.
  | { state: 'stopped'; message: string };

export interface BackendConnection {
  status: BackendStatus;
  /** Non-null exactly when `status.state === 'ready'`. */
  api: BackendApi | null;
  dataDir: string | null;
  /**
   * Whether the last request got through. False after a transport failure,
   * true again as soon as anything answers.
   *
   * Separate from `status`, which reports the process: the shell can only see
   * the backend die, while this sees the connection to it fail - a firewall
   * prompt, a request issued a moment too early on a cold start.
   */
  reachable: boolean;
}

export function useBackend(): BackendConnection {
  const [status, setStatus] = useState<BackendStatus>({ state: 'starting' });
  const [reachable, setReachable] = useState(true);

  useEffect(() => {
    let active = true;

    const unlistenPromise = listen<BackendStatus>('backend://status', (event) => {
      if (active) setStatus(event.payload);
    });

    // Covers the case where the backend became ready before this effect ran.
    invoke<BackendStatus>('backend_status')
      .then((current) => {
        // Never downgrade a status the event already delivered.
        if (active) setStatus((previous) => (previous.state === 'starting' ? current : previous));
      })
      .catch((error: unknown) => {
        if (active) {
          setStatus({
            state: 'failed',
            message: `Cannot query the backend supervisor: ${String(error)}`,
          });
        }
      });

    return () => {
      active = false;
      void unlistenPromise.then((unlisten) => unlisten());
    };
  }, []);

  const api = useMemo(
    () =>
      status.state === 'ready'
        // setState with the same value is a no-op in React, so the common case
        // - every successful request reporting "still reachable" - costs
        // nothing and does not re-render.
        ? new BackendApi(status.base_url, status.api_key, setReachable)
        : null,
    [status],
  );

  return {
    status,
    api,
    dataDir: status.state === 'ready' ? status.data_dir : null,
    reachable,
  };
}
