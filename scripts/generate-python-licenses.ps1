<#
.SYNOPSIS
    Writes licenses/LICENSES-python.txt - the notice file for every Python
    package embedded in the frozen backend.

.DESCRIPTION
    The backend ships as a PyInstaller bundle, so CPython and its whole
    dependency tree are redistributed inside the MSIX. MIT, BSD and Apache-2.0
    all require their notice to travel with the binary, which means the text has
    to be in the package - not merely referenced from the repository.

    This reads the licence metadata out of the backend virtualenv with
    pip-licenses and renders one section per package. A handful of wheels ship
    no licence file at all; for those the text is fetched from the project's own
    repository, recorded in $fallbackLicenseUrls below. A package with neither
    is a hard failure: a new dependency must not be able to slip into the bundle
    with nothing to show for its licence.

    Re-run this after changing backend dependencies. The output is committed, so
    a release build does not need the network.

.PARAMETER SkipFallbackDownload
    Renders "UNKNOWN" for the packages that need a fetched licence instead of
    downloading it. Offline convenience only - the result is not shippable.
#>
[CmdletBinding()]
param(
    [switch]$SkipFallbackDownload
)

$ErrorActionPreference = "Stop"

$projectDir = Split-Path $PSScriptRoot -Parent
$backendDir = Join-Path $projectDir "backend"
$outputPath = Join-Path $projectDir "licenses\LICENSES-python.txt"

# Packages whose wheel carries no licence text. The URL is the licence file in
# the project's own repository - the same terms the metadata declares, in full.
$fallbackLicenseUrls = @{
    "ctranslate2" = "https://raw.githubusercontent.com/OpenNMT/CTranslate2/master/LICENSE"
    "flatbuffers" = "https://raw.githubusercontent.com/google/flatbuffers/master/LICENSE"
    "loguru"      = "https://raw.githubusercontent.com/Delgan/loguru/master/LICENSE"
    "tokenizers"  = "https://raw.githubusercontent.com/huggingface/tokenizers/main/LICENSE"
}

# pip-licenses and its own dependencies are installed into the ephemeral uv
# overlay for this run; they are a tool, not part of the bundle.
$toolPackages = @("pip-licenses", "prettytable", "wcwidth")

if (-not (Test-Path (Join-Path $backendDir ".venv"))) {
    throw "No virtualenv at $backendDir\.venv. Run 'uv sync' in backend first."
}

$tempCsv = Join-Path ([System.IO.Path]::GetTempPath()) "cliparchitect-pylicenses.csv"

Write-Host "Reading licence metadata from the backend virtualenv..."
Push-Location $backendDir
try {
    & uv run --with pip-licenses pip-licenses `
        --format=csv --with-urls --with-license-file --no-license-path `
        --ignore-packages @toolPackages --output-file $tempCsv
    if ($LASTEXITCODE -ne 0) { throw "pip-licenses failed with exit code $LASTEXITCODE." }
} finally {
    Pop-Location
}

$packages = Import-Csv $tempCsv | Sort-Object { $_.Name.ToLowerInvariant() }
Remove-Item $tempCsv -Force -ErrorAction SilentlyContinue
if (-not $packages) { throw "pip-licenses returned no packages." }

$fetched = @{}
$builder = New-Object System.Text.StringBuilder
$rule = "=" * 78

[void]$builder.AppendLine(@"
Python dependency licenses
==========================

The Clip Architect backend ships as a frozen PyInstaller bundle, so its
dependencies are redistributed inside the application. This file reproduces the
licence each one is distributed under.

It is written from the backend virtualenv, which is what PyInstaller freezes
from, so a few development-only entries (the test runner, the packaging tool)
are listed here as well. They are left in rather than filtered out: listing a
licence for something that did not ship misleads nobody, and filtering by hand
is how a package that does ship stops being listed.

Generated by scripts/generate-python-licenses.ps1 on $(Get-Date -Format 'yyyy-MM-dd') from the
backend virtualenv - $($packages.Count) packages. Do not edit by hand; re-run the script.

Clip Architect itself is licensed under GPL-3.0 (licenses/LICENSE.txt), and the
other components it bundles - FFmpeg, the subtitle fonts, the upstream
MoneyPrinterTurbo code - are covered in licenses/THIRD-PARTY-NOTICES.md.

"@)

foreach ($package in $packages) {
    $text = $package.LicenseText
    if ($text -eq "UNKNOWN" -or [string]::IsNullOrWhiteSpace($text)) {
        $url = $fallbackLicenseUrls[$package.Name]
        if (-not $url) {
            throw @"
$($package.Name) $($package.Version) ships no licence text in its wheel and has no
fallback recorded. Add its licence file URL to `$fallbackLicenseUrls in
scripts/generate-python-licenses.ps1, or the package would ship with its
$($package.License) notice missing.
"@
        }
        if ($SkipFallbackDownload) {
            $text = "UNKNOWN - not fetched (-SkipFallbackDownload)."
        } elseif ($fetched.ContainsKey($url)) {
            $text = $fetched[$url]
        } else {
            Write-Host "  fetching licence text for $($package.Name)..."
            $text = (Invoke-WebRequest -Uri $url -UseBasicParsing).Content
            $text = "$($text.TrimEnd())`r`n`r`n[Retrieved from $url]"
            $fetched[$url] = $text
        }
    }

    [void]$builder.AppendLine($rule)
    [void]$builder.AppendLine("$($package.Name) $($package.Version)")
    [void]$builder.AppendLine($package.License)
    if ($package.URL -and $package.URL -ne "UNKNOWN") {
        [void]$builder.AppendLine($package.URL)
    }
    [void]$builder.AppendLine($rule)
    [void]$builder.AppendLine()
    [void]$builder.AppendLine($text.Replace("`r`n", "`n").TrimEnd())
    [void]$builder.AppendLine()
}

$outputDir = Split-Path $outputPath -Parent
if (-not (Test-Path $outputDir)) { New-Item -ItemType Directory -Path $outputDir -Force | Out-Null }
$builder.ToString() | Out-File $outputPath -Encoding utf8

$sizeKb = [Math]::Round((Get-Item $outputPath).Length / 1KB, 1)
Write-Host "Wrote $outputPath ($($packages.Count) packages, $sizeKb KB)."
